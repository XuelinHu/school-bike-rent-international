CREATE TABLE users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username VARCHAR(50) NOT NULL,
  password VARCHAR(255) NOT NULL,
  name VARCHAR(100),
  email VARCHAR(120),
  phone VARCHAR(30),
  role TEXT NOT NULL DEFAULT 'student' CHECK (role IN ('student', 'admin', 'staff')),
  student_no VARCHAR(50),
  nationality VARCHAR(80),
  language VARCHAR(20) DEFAULT 'zh-CN',
  status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'disabled')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE stations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name_zh VARCHAR(120) NOT NULL,
  name_en VARCHAR(120) NOT NULL,
  address_zh VARCHAR(255),
  address_en VARCHAR(255),
  latitude NUMERIC(10, 7),
  longitude NUMERIC(10, 7),
  capacity INTEGER NOT NULL DEFAULT 0 CHECK (capacity >= 0),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE bikes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  bike_no VARCHAR(60) NOT NULL UNIQUE,
  name VARCHAR(120),
  type VARCHAR(60),
  status TEXT NOT NULL DEFAULT 'available' CHECK (status IN ('available', 'rented', 'maintenance', 'disabled')),
  station_id BIGINT REFERENCES stations(id) ON DELETE SET NULL,
  hourly_rate NUMERIC(10, 2) NOT NULL DEFAULT 2.00 CHECK (hourly_rate >= 0),
  image_url VARCHAR(500),
  description TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE rental_orders (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_no VARCHAR(80) NOT NULL UNIQUE,
  user_id BIGINT NOT NULL REFERENCES users(id),
  bike_id BIGINT NOT NULL REFERENCES bikes(id),
  start_time TIMESTAMPTZ NOT NULL,
  end_time TIMESTAMPTZ,
  duration_hours INTEGER CHECK (duration_hours IS NULL OR duration_hours > 0),
  hourly_rate NUMERIC(10, 2) NOT NULL DEFAULT 2.00 CHECK (hourly_rate >= 0),
  total_amount NUMERIC(10, 2) DEFAULT 0 CHECK (total_amount IS NULL OR total_amount >= 0),
  status TEXT NOT NULL DEFAULT 'renting' CHECK (status IN ('renting', 'completed', 'cancelled')),
  start_station_id BIGINT,
  end_station_id BIGINT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE maintenance_records (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  bike_id BIGINT NOT NULL REFERENCES bikes(id),
  staff_id BIGINT REFERENCES users(id),
  content TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'processing' CHECK (status IN ('processing', 'finished')),
  start_time TIMESTAMPTZ,
  end_time TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE announcements (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title_zh VARCHAR(200) NOT NULL,
  title_en VARCHAR(200) NOT NULL,
  content_zh TEXT NOT NULL,
  content_en TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'published' CHECK (status IN ('published', 'hidden')),
  created_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX idx_orders_user_status ON rental_orders (user_id, status);
CREATE INDEX idx_orders_bike ON rental_orders (bike_id);
CREATE INDEX idx_orders_start_station ON rental_orders (start_station_id);
CREATE INDEX idx_orders_end_station ON rental_orders (end_station_id);
CREATE INDEX idx_bikes_station ON bikes (station_id);
CREATE INDEX idx_maintenance_bike ON maintenance_records (bike_id);
CREATE INDEX idx_maintenance_staff ON maintenance_records (staff_id);
CREATE INDEX idx_announcements_created_by ON announcements (created_by);
CREATE UNIQUE INDEX uniq_users_username_casefold ON users (lower(username));

CREATE FUNCTION touch_updated_at() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$;

CREATE TRIGGER users_touch_updated_at BEFORE UPDATE ON users FOR EACH ROW EXECUTE FUNCTION touch_updated_at();
CREATE TRIGGER stations_touch_updated_at BEFORE UPDATE ON stations FOR EACH ROW EXECUTE FUNCTION touch_updated_at();
CREATE TRIGGER bikes_touch_updated_at BEFORE UPDATE ON bikes FOR EACH ROW EXECUTE FUNCTION touch_updated_at();
CREATE TRIGGER rental_orders_touch_updated_at BEFORE UPDATE ON rental_orders FOR EACH ROW EXECUTE FUNCTION touch_updated_at();
CREATE TRIGGER maintenance_records_touch_updated_at BEFORE UPDATE ON maintenance_records FOR EACH ROW EXECUTE FUNCTION touch_updated_at();
CREATE TRIGGER announcements_touch_updated_at BEFORE UPDATE ON announcements FOR EACH ROW EXECUTE FUNCTION touch_updated_at();
